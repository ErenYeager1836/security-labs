"""
Command line interface for hardening-auditor.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import sys

# Ensure parent directory is in sys.path when invoked directly as a script
_pkg_root = Path(__file__).resolve().parent.parent
if str(_pkg_root) not in sys.path:
    sys.path.insert(0, str(_pkg_root))

from hardening_auditor.engine import run_system_audit
from hardening_auditor.models import AuditSummary, RuleResult, RuleStatus, Severity


def format_markdown_report(summary: AuditSummary, target_root: str) -> str:
    """Generates a comprehensive Markdown report with compliance score and remediation steps."""
    md: list[str] = [
        "# Linux System Hardening Compliance Audit Report",
        f"**Target Filesystem Root:** `{target_root}`  ",
        f"**Audit Score:** **{summary.score_percentage}%**  ",
        f"**Summary:** {summary.passed_rules} Passed, {summary.failed_rules} Failed, {summary.skipped_rules} Skipped  ",
        f"**Critical / High Severity Failures:** {summary.critical_failures} Critical / {summary.high_failures} High  ",
        "",
        "---",
        "",
        "## 1. Compliance Scorecard",
        "",
        "| Rule ID | Category | Title | Severity | Status | Current Value | Expected Value |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
    ]

    for r in summary.results:
        status_badge = f"**{r.status.value}**"
        md.append(f"| `{r.rule_id}` | {r.category} | {r.title} | {r.severity} | {status_badge} | `{r.current_value}` | `{r.expected_value}` |")

    md.extend([
        "",
        "---",
        "",
        "## 2. Hardening Remediation Commands",
        "",
        "> [!IMPORTANT]",
        "> The hardening auditor operates strictly in **read-only mode**. The following commands must be reviewed and executed by a system administrator to remediate non-compliant configurations.",
        "",
        "```bash",
        "#!/usr/bin/env bash",
        "# Security Hardening Remediation Script",
        "set -euo pipefail",
        "",
    ])

    failed_rules = [r for r in summary.results if r.status == RuleStatus.FAIL]
    if not failed_rules:
        md.append("# All audited checks passed! System meets baseline CIS hardening standards.")
    else:
        for r in failed_rules:
            md.append(f"# [{r.rule_id}] {r.title} ({r.severity})")
            md.append(f"# Rationale: {r.rationale}")
            md.append(f"{r.remediation}")
            md.append("")

    md.extend([
        "```",
        "",
        "---",
        "*Report generated by `hardening-auditor v0.1.0`*",
    ])
    return "\n".join(md)


def main() -> int:
    parser = argparse.ArgumentParser(
        prog="hardening-auditor",
        description="Read-only CIS-style security compliance auditor for Linux configurations, file permissions, ports, and sudo.",
    )
    parser.add_argument(
        "--root",
        type=str,
        default=None,
        help="Root directory to audit (default: '/' on Linux, or autodetected mock directory on Windows).",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=str,
        default=None,
        help="Optional path to output Markdown audit report.",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Output results as raw JSON to stdout.",
    )
    parser.add_argument(
        "--fixes-only",
        action="store_true",
        help="Print only failed rules and remediation commands.",
    )

    args = parser.parse_args()

    # Determine default audit target
    if args.root:
        target_root = Path(args.root)
    else:
        if os.name == "nt" or not Path("/etc").exists():
            # Running on Windows or non-Linux without /etc, default to sample mock config
            sample_dir = Path(__file__).resolve().parent.parent / "sample_configs" / "unhardened"
            if sample_dir.exists():
                target_root = sample_dir
            else:
                target_root = Path("/")
        else:
            target_root = Path("/")

    summary = run_system_audit(target_root)

    if args.json:
        data = {
            "target_root": str(target_root),
            "score_percentage": summary.score_percentage,
            "passed": summary.passed_rules,
            "failed": summary.failed_rules,
            "skipped": summary.skipped_rules,
            "critical_failures": summary.critical_failures,
            "high_failures": summary.high_failures,
            "results": [
                {
                    "rule_id": r.rule_id,
                    "title": r.title,
                    "category": r.category,
                    "severity": r.severity,
                    "status": r.status.value,
                    "current_value": r.current_value,
                    "expected_value": r.expected_value,
                    "remediation": r.remediation,
                    "rationale": r.rationale,
                }
                for r in summary.results
            ],
        }
        print(json.dumps(data, indent=2))
        return 0

    print("=" * 64)
    print("      security-labs // hardening-auditor (Python)       ")
    print("      CIS-Style Read-Only Linux Security Auditor        ")
    print("=" * 64)
    print(f"[*] Target Directory Root : {target_root.resolve()}")
    print(f"[*] Total Controls Audited: {summary.total_rules}")
    print(f"[+] Passed Controls       : {summary.passed_rules}")
    print(f"[-] Failed Controls       : {summary.failed_rules}")
    print(f"[~] Skipped Controls      : {summary.skipped_rules}")
    print(f"[*] Compliance Score      : {summary.score_percentage}%")
    print("-" * 64)

    # Group by category
    categories: dict[str, list[RuleResult]] = {}
    for r in summary.results:
        categories.setdefault(r.category, []).append(r)

    for cat_name, cat_rules in categories.items():
        print(f"\n[+] Category: {cat_name}")
        for r in cat_rules:
            if args.fixes_only and r.status != RuleStatus.FAIL:
                continue

            tag = f"[{r.status.value}]"
            sev = f"({r.severity})"
            print(f"  {tag:<8} {r.rule_id}: {r.title} {sev}")
            print(f"           Current:  {r.current_value}")
            if r.status == RuleStatus.FAIL:
                print(f"           Expected: {r.expected_value}")
                print(f"           Fix:      {r.remediation}")

    print("\n" + "=" * 64)
    print("               RECOMMENDED REMEDIATION COMMANDS                ")
    print("=" * 64)
    failed_rules = [r for r in summary.results if r.status == RuleStatus.FAIL]
    if not failed_rules:
        print("[+] System conforms to audited baseline. No remediation required.")
    else:
        print("# Execute with root / sudo permissions after reviewing impact:")
        for idx, r in enumerate(failed_rules, 1):
            print(f"#{idx}. [{r.rule_id}] {r.title}")
            print(f"{r.remediation}")

    print("\n[!] NOTE: hardening-auditor is read-only. No system changes were applied.")

    if args.output:
        report_content = format_markdown_report(summary, str(target_root.resolve()))
        out_path = Path(args.output)
        out_path.write_text(report_content, encoding="utf-8")
        print(f"[+] Detailed report exported to: {out_path.resolve()}")

    return 0 if summary.failed_rules == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
